def _pace_gap_rows(dist_km, pairs):
    """두 목표 사이의 km당 페이스 차이를 보여 준다."""
    rows = []
    for a, b in pairs:
        pa, pb = a / dist_km, b / dist_km
        rows.append([T.hms(a), T.pace(pa) + " /km", T.hms(b),
                     T.pace(pb) + " /km", f"{int(round(pa - pb))}초"])
    return rows


