import guide_tables as T
import wma_standards as wma

AGES = [20, 30, 40, 50, 60, 70]


def next_tier_rows(dist_key, targets_sec, age, gender):
    """목표 시간별로 — 지금 등급, 다음 등급, 거기까지 줄여야 하는 시간.

    다음 등급의 하한 연령등급 %를 만족하는 기록을 역산해서 차이를 낸다.
    등급 구간이나 WMA 표가 바뀌면 이 숫자도 같이 따라온다.
    """
    rows = []
    for t in targets_sec:
        pct = wma.age_grade(t, gender, dist_key, age)
        cur = T.tier_of(pct)
        nxt = None
        for bound, label in T.TIER_BOUNDS:
            if bound > pct:
                nxt = (bound, label)
        if nxt is None:
            rows.append([T.hms(t), f"{pct:.0f}% · {cur}", "최상위 구간", "—"])
            continue
        bound, label = nxt
        target = wma.standard(gender, dist_key, age) / (bound / 100.0)
        gap = t - target
        m, s = divmod(int(round(gap)), 60)
        rows.append([
            T.hms(t), f"{pct:.0f}% · {cur}", label,
            f"{T.hms(target)} (−{m}분 {s:02d}초)",
        ])
    return rows


