def wind_chill(ta, v_ms):
    """기상청 겨울철 체감온도. V 는 km/h 로 넣는다. 기온 10℃ 이하, 풍속 1.3 m/s 이상에서만 유효."""
    v = v_ms * 3.6
    return round(13.12 + 0.6215 * ta - 11.37 * v ** 0.16 + 0.3965 * v ** 0.16 * ta)


def _wc_rows():
    winds = (1.4, 3, 5, 8)
    return [[f"{t}℃"] + [f"{wind_chill(t, w)}℃" for w in winds] for t in (5, 0, -5, -10)]


