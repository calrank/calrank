def _countdown(start_hm, meal_h):
    """출발 시각에서 거꾸로 센 당일 일정.

    집결은 보통 출발 한 시간 전이고, 물품보관과 화장실 줄을 생각하면
    그보다 더 일찍 도착해야 합니다. 손으로 적으면 반드시 어긋나므로
    출발 시각만 주면 나머지가 계산되게 해 둡니다.
    """
    h, m = start_hm
    start = h * 60 + m

    def at(minus):
        t = (start - minus) % (24 * 60)
        return f"{t // 60:02d}:{t % 60:02d}"

    return [
        [at(meal_h * 60 + 30), "기상"],
        [at(meal_h * 60), f"아침 식사 (출발 {meal_h}시간 전)"],
        [at(150), "수분 섭취 — 체중 1kg당 5~10 mL"],
        [at(120), "출발, 이동"],
        [at(60), "도착 · 물품보관 · 화장실"],
        [at(40), "워밍업 시작"],
        [at(20), "집결 · 필요하면 가볍게 보충"],
        [at(0), "출발"],
    ]


